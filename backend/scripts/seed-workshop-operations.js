async function seed() {
  const lines = rawCsv.trim().split('\n');
  console.log(`Cargando ${lines.length} operaciones al catálogo maestro...`);

  let count = 0;
  for (const line of lines) {
    const parts = line.split(',');
    if (parts.length < 4) continue;
    const code = parts[0].trim();
    // Limpieza de caracteres extraños como ¥ (e.g. CIGUEÑAL)
    let desc = parts[1].trim().replace(/¥/g, 'Ñ');
    const hoursCars = parseFloat(parts[2].trim()) || 0;
    const hoursTrucks = parseFloat(parts[3].trim()) || 0;

    let category = 'MECANICA';
    const upper = desc.toUpperCase();
    if (upper.includes('LAVADO') || upper.includes('PULIDO')) {
      category = 'LAVADO';
    } else if (upper.includes('HOJALATERI') || upper.includes('PINTURA')) {
      category = 'HYP';
    } else if (upper.includes('MTTO') || upper.includes('MANTENIMIENTO') || upper.includes('PREVIA')) {
      category = 'MANTENIMIENTO';
    } else if (upper.includes('DIAGNOSTICO') || upper.includes('ESCANEADO')) {
      category = 'DIAGNOSTICO';
    }

    await prisma.workshopOperation.upsert({
      where: { code },
      update: {
        description: desc,
        hoursCars,
        hoursTrucks,
        category,
        active: true,
      },
      create: {
        code,
        description: desc,
        hoursCars,
        hoursTrucks,
        category,
        active: true,
      },
    });
    count++;
  }

  console.log(`¡Éxito! ${count} operaciones guardadas en el catálogo maestro (workshop_operations).`);
  await prisma.$disconnect();
}

seed().catch((err) => {
  console.error(err);
  process.exit(1);
});
